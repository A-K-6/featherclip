pub fn needs_gnome_bridge() -> bool {
    cfg!(target_os = "linux")
        && std::env::var_os("WAYLAND_DISPLAY").is_some()
        && std::env::var("XDG_CURRENT_DESKTOP")
            .unwrap_or_default()
            .to_lowercase()
            .contains("gnome")
}

pub enum Clipboard {
    #[cfg(target_os = "macos")]
    Apple(objc2::rc::Retained<objc2_app_kit::NSPasteboard>, isize),
    #[cfg(target_os = "linux")]
    Native(arboard::Clipboard),
    #[cfg(target_os = "linux")]
    Gnome(gio::DBusConnection),
    /// Synthetic data only, for release smoke checks; never touches the real clipboard.
    Demo(Option<String>),
}

impl Clipboard {
    pub fn new(demo: bool) -> Result<Self, String> {
        if demo {
            return Ok(Self::Demo(None));
        }
        #[cfg(target_os = "linux")]
        if needs_gnome_bridge() {
            return gio::bus_get_sync(gio::BusType::Session, gio::Cancellable::NONE)
                .map(Self::Gnome)
                .map_err(|_| "Couldn't connect to the desktop session.".into());
        }
        #[cfg(target_os = "macos")]
        {
            Ok(Self::Apple(
                objc2_app_kit::NSPasteboard::generalPasteboard(),
                -1,
            ))
        }
        #[cfg(target_os = "linux")]
        {
            arboard::Clipboard::new().map(Self::Native).map_err(|_| {
                "Couldn't connect to the clipboard. Start FeatherClip inside your desktop session."
                    .into()
            })
        }
    }

    pub fn changed(&mut self) -> bool {
        #[cfg(target_os = "macos")]
        if let Self::Apple(board, last_count) = self {
            let count = board.changeCount();
            if count == *last_count {
                return false;
            }
            *last_count = count;
        }
        true
    }

    pub fn read(&mut self) -> Result<Option<String>, String> {
        match self {
            Self::Demo(text) => Ok(text.clone()),
            #[cfg(target_os = "macos")]
            Self::Apple(board, _) => objc2::rc::autoreleasepool(|_| {
                let count = board.changeCount();
                let excluded = [
                    "org.nspasteboard.ConcealedType",
                    "org.nspasteboard.TransientType",
                    "org.nspasteboard.AutoGeneratedType",
                    "com.agilebits.onepassword",
                    "public.file-url",
                ];
                let types = board.types();
                if types.is_some_and(|types| {
                    types
                        .iter()
                        .any(|t| excluded.contains(&t.to_string().as_str()))
                }) {
                    return Ok(None);
                }
                let text = unsafe { board.stringForType(objc2_app_kit::NSPasteboardTypeString) }
                    .map(|text| text.to_string());
                Ok(if count == board.changeCount() {
                    text
                } else {
                    None
                })
            }),
            #[cfg(target_os = "linux")]
            Self::Native(clipboard) => match clipboard.get_text() {
                Ok(text) => Ok(Some(text)),
                Err(arboard::Error::ContentNotAvailable) => Ok(None),
                Err(_) => Err(
                    "Clipboard access is unavailable. Check your system's clipboard permissions."
                        .into(),
                ),
            },
            #[cfg(target_os = "linux")]
            Self::Gnome(connection) => {
                let value = connection
                    .call_sync(
                        Some("io.github.AK6.FeatherClip.Gnome"),
                        "/io/github/AK6/FeatherClip/Gnome",
                        "io.github.AK6.FeatherClip.Gnome",
                        "ReadText",
                        None,
                        None,
                        gio::DBusCallFlags::NONE,
                        1500,
                        gio::Cancellable::NONE,
                    )
                    .map_err(|_| gnome_help())?;
                value
                    .get::<(String,)>()
                    .map(|(text,)| Some(text))
                    .ok_or_else(|| "The GNOME bridge returned an unexpected response.".into())
            }
        }
    }

    pub fn write(&mut self, text: String) -> Result<(), String> {
        match self {
            Self::Demo(value) => {
                *value = Some(text);
                Ok(())
            }
            #[cfg(target_os = "macos")]
            Self::Apple(board, _) => objc2::rc::autoreleasepool(|_| unsafe {
                board.clearContents();
                if board.setString_forType(
                    &objc2_foundation::NSString::from_str(&text),
                    objc2_app_kit::NSPasteboardTypeString,
                ) {
                    Ok(())
                } else {
                    Err("Couldn't copy this clip. Please try again.".into())
                }
            }),
            #[cfg(target_os = "linux")]
            Self::Native(clipboard) => clipboard
                .set_text(text)
                .map_err(|_| "Couldn't copy this clip. Please try again.".into()),
            #[cfg(target_os = "linux")]
            Self::Gnome(connection) => {
                use glib::variant::ToVariant;
                connection
                    .call_sync(
                        Some("io.github.AK6.FeatherClip.Gnome"),
                        "/io/github/AK6/FeatherClip/Gnome",
                        "io.github.AK6.FeatherClip.Gnome",
                        "WriteText",
                        Some(&(text,).to_variant()),
                        None,
                        gio::DBusCallFlags::NONE,
                        1500,
                        gio::Cancellable::NONE,
                    )
                    .map(|_| ())
                    .map_err(|_| gnome_help())
            }
        }
    }
}

#[cfg(all(test, target_os = "macos"))]
mod tests {
    use super::*;
    use objc2_app_kit::NSPasteboard;
    use objc2_foundation::NSString;

    #[test]
    fn mac_pasteboard_roundtrip_and_concealed_text_exclusion() {
        // A unique pasteboard exercises the actual OS API without touching personal clips.
        let board = NSPasteboard::pasteboardWithUniqueName();
        let mut clipboard = Clipboard::Apple(board.clone(), -1);
        let text = "سلام 👋\nexact text\t ";
        clipboard.write(text.into()).unwrap();
        assert!(clipboard.changed());
        assert!(!clipboard.changed());
        assert_eq!(clipboard.read().unwrap().as_deref(), Some(text));
        board.setString_forType(
            &NSString::from_str(""),
            &NSString::from_str("org.nspasteboard.ConcealedType"),
        );
        assert_eq!(clipboard.read().unwrap(), None);
        let _: () = unsafe { objc2::msg_send![&*board, releaseGlobally] };
    }
}

#[cfg(all(test, target_os = "linux"))]
mod linux_tests {
    use super::*;

    #[test]
    #[ignore = "Run only under an isolated Xvfb display, never on a user's desktop"]
    fn isolated_x11_clipboard_roundtrip() {
        assert!(std::env::var("FEATHERCLIP_ISOLATED_DISPLAY").is_ok());
        let mut clipboard = Clipboard::new(false).unwrap();
        let text = "FeatherClip isolated integration test — سلام 👋";
        clipboard.write(text.into()).unwrap();
        assert_eq!(clipboard.read().unwrap().as_deref(), Some(text));
    }
}

